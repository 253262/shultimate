# -*- coding: utf-8 -*-
"""轻量对话路：识别「根本不是规则问题」的提问（寒暄 / 元问题 / 问助手本身）。

**为什么要有它**（2026-10-06 owner 实测报的）
Owner 问「我有什么飞盘不懂得规则可以问你吗」，系统回了一整屏 ——
**结论 / 依据 / 该怎么做 / 规则没规定的部分 / 还需确认**（那套五段结构
当晚已整体删除，见 `tests/test_answer_shape.py`），里面还写
「规则没有规定"可以问谁""问几次"这类细节」。他原话：

  「有点答非所问了」「就像人和人之间的对话一样，我问你一句话，你回一句就行了」
  「他其实问的不是关于飞盘规则的问题」

根因**不是检索错，是流程错**：
  这句话里含「飞盘」「规则」两个域内词 ⇒ 闸门放行 ⇒ 走完整 RAG ⇒
  检索到 10.1.2 / 1.8 / 1.9 这些「鼓励向别人请教规则」的条款 ⇒
  再被 SYSTEM_PROMPT 的固定结构套成五段。**问题本身压根不是规则问题。**

⇒ 判据 = **明确句式 + 不含任何规则场景**。三道门都必须过：

  ① 命中 META_HINTS —— 句式要**具体到只有闲聊/元问题才会这么说**，
     绝不收「你能 / 怎么样 / 什么意思」这种宽词（宽词会把真规则题卷进来）。
  ② `routes.match_routes()` 为空 —— 真规则题几乎必然带动作线索词
     （犯规 / 读秒 / 走步 / 换人 …）。
  ③ 域内词只能剩下 {飞盘, 盘, 规则} —— 出现任何别的域内词
     （场地 / 球衣 / 边线 / 暂停 …）就说明他在问具体规则。
     这一道是**兜住 ② 的结构性漏洞**：368 条规则里有 190 条不属于任何族
     （场地 / 装备 / 队伍等事实性章节），光看 ② 会漏。
     例：「你好，球衣能穿什么」—— 有「你好」、可能没族，但含「球衣」⇒ 不算闲聊 ✅

⚠️ **方向必须「宁漏勿错」**：把真规则题误判成闲聊，模型就会凭记忆答规则
   （可能编造，比"多说了几句"坏得多）⇒ 判不准就**按规则问题走**。
   兜底还有一层：CHAT_SYSTEM 里写明「发现他在问具体场上情形就交回流程」，
   所以最坏情况是"这个我得查规则"，而不是一个编出来的答案。

⚠️ 本模块**只决定走哪条路，不参与任何打分**（与 `routes.DOMAIN_WORDS` 同规矩）。
"""
from __future__ import annotations

from . import routes

# 明确句式。加词前先自问：**只有闲聊/元问题会这么说吗？**
# ⚠️ 别收"自我介绍"：规则 1.5.4 的原话就是「主动向对手自我介绍」，
#    收了它这条规则正文会被判成闲聊（实证探针真的抓到了）。
#    面向助手的自我介绍靠「介绍一下你」覆盖，够用。
META_HINTS: list[str] = [
    # ── A. 元问题：能不能问你 / 问几次 ──────────────────────────
    "能不能问", "能不能请教", "可以问", "能问", "问一下你", "问你个",
    "问你一个", "问你问题", "提问", "请教", "咨询你",
    "问几个", "问几次", "问多少", "问多久", "问几遍", "有次数限制",
    # ── B. 关于助手 / 系统本身 ─────────────────────────────────
    "你是谁", "你是什么", "你是啥", "你叫什么", "介绍一下你",
    # ⚠️ 2026-10-13 补：`我是谁` / `我在哪` 是**对称的元问题** ——
    #    用户在确认"我在跟什么东西说话"。原来没覆盖 ⇒ 掉到范围闸门 ⇒
    #    被判成**离题**（"这个不在我管的范围里"），
    #    而正确答案应该是"我是飞盘规则助手，我在帮你查规则"。
    #    发现途径：埋点报表里看到 `route=off_topic q=我是谁`。
    "我是谁", "我在哪", "我在哪儿", "这是哪",
    # ⚠️ 刻意**不收**「这是什么」—— 它太短，会被当成子串命中
    #    「我是谁不重要，规则怎么写的」这类**真规则问题**（实测踩过）。
    #    要问"你是什么"，用上面的「你是什么 / 你是谁」。
    "你能做什么", "你能干嘛", "你能干什么", "你会什么", "有什么功能",
    "怎么用", "如何使用", "怎么使用", "咋用",
    "你懂", "你靠谱", "你会答错", "你会不会答错", "你准不", "准确率",
    # ── C. 寒暄 / 社交 ────────────────────────────────────────
    "你好", "您好", "哈喽", "hello", "在吗", "在么",
    "早上好", "中午好", "下午好", "晚上好",
    "谢谢", "多谢", "感谢", "辛苦了", "再见", "拜拜",
]

# 闲聊里天然会出现的域内词 —— **只有这三个**。
# ⚠️ 别往里加。加一个就等于给"具体规则问题"开一个口子：
#    例：把「比赛」放进来，「打完比赛之后能换人吗」就再也不是规则题了。
META_ALLOWED_DOMAIN: frozenset[str] = frozenset({"飞盘", "盘", "规则"})


def _domain_words(text: str) -> list[str]:
    """问题里出现的**全部**域内词（`routes.domain_hit` 只返回第一个）。

    ⚠️⚠️ 2026-10-10 修：原来这里**只扫中文 `DOMAIN_WORDS`**，漏掉了英文术语，
       于是官方术语问句在闲聊判定里"没有域内证据"：
           「pivot怎么用」→ is_smalltalk=True → 走闲聊路
           「force怎么用」→ 同上
       实测这两条拿不到任何规则解释 —— 新手问"轴心怎么转"却只得到一句客套话。
       而 `spirit是什么`/`turnover是什么` 侥幸没中，只是因为它们的问法
       恰好还带了别的信号 —— **侥幸，不是设计**。

       ⇒ 必须和 `routes.domain_hit` 用**同一套**判据（含 TERM_ALIASES）。
         否则两处对「这是不是飞盘问题」的判断不一致 ⇒ 同一句话
         一处放行、一处判闲聊，谁先跑谁赢，纯看调用顺序。
    """
    low = routes._norm(text)
    words = [w for w in routes.DOMAIN_WORDS if w in low]
    # 英文术语必须走 `routes.term_aliases_in()` 这一个入口 ——
    # ⚠️ 不要在这里自己 `for w in TERM_ALIASES: if _alias_in(...)`：
    #   那样会漏掉「飞盘独有的词」与「需要语境陪衬的词」的分档，
    #   实测「force怎么用」就是这样被漏掉、又落回闲聊路的
    #   （force 是通用词，`force of habit` 会误报 ⇒ 必须要有陪衬）。
    words += routes.term_aliases_in(low)
    return words


def is_smalltalk(text: str) -> bool:
    """这句是不是「不是规则问题」？是就返回 True，走轻量对话路。"""
    t = (text or "").strip()
    if not t:
        return False
    low = routes._norm(t)

    # ① 必须是明确句式
    if not any(h in low for h in META_HINTS):
        return False
    # ② 命中任何族 ⇒ 这是规则题
    if routes.match_routes(low):
        return False
    # ③ 域内词只能剩下"飞盘 / 盘 / 规则"
    if any(w not in META_ALLOWED_DOMAIN for w in _domain_words(low)):
        return False
    # ④ ⚠️ **句子里有"求答案"的信号 ⇒ 这不是闲聊**（2026-10-13 加）
    #
    # 为什么需要这条：`META_HINTS` 是**子串匹配**，而中文没有词边界 ——
    # 一旦把某个短句加进词表，它就会命中任何**包含它**的长句。
    # 实测：加了「我是谁」之后，「我是谁不重要，**规则怎么写的**」
    # 被判成闲聊 ⇒ 一个真规则问题被送去了轻量对话路。
    #
    # ⚠️ 方向与本项目一贯的「**误拦 = 实质答错**」一致：
    #    宁可把一句真闲聊当规则题多跑一次检索（白花一点时间），
    #    也不能把真规则问题当闲聊（用户拿不到条款）。
    # ⚠️ 这份信号表**刻意只放"在要一个答案"的词**，不放域内词 ——
    #    域内词已经由 ②③ 管了，混在一起会互相抵消。
    if any(sig in low for sig in _RULE_SEEKING):
        return False
    return True


# ⚠️ 「在要一个答案」的信号（不是域内词）。
#    出现在句子里 ⇒ 这句话是来问事的，不是来寒暄的。
_RULE_SEEKING = (
    "怎么", "怎样", "如何", "为什么", "为啥", "多少", "几种", "哪个",
    "算不算", "算吗", "行不行", "可以吗", "能不能", "该不该", "要不要",
    "有没有", "是不是", "对不对", "吗？", "吗?", "呢？", "呢?",
    "规定", "条款", "第几条",
)
