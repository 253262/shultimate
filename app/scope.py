"""⭕ **范围与意图闸门** —— 决定一句话该走哪条路（2026-10-13 owner 定的底层逻辑）。

## 为什么需要它
产品最初只答规则。但 owner 发现：

> 「用户可能会问到规则之外的问题。比如说，今天被打爆了，心情确实不好，
>  但这不属于飞盘规则。…他本来就因为被打爆了而难过，结果向你提问飞盘规则
>  之外的相关内容时，你又回答不出来，**这会让他更难过。我们不能让用户难过。**」

⇒ 产品要同时做三件事：**答对规则 + 接住情绪 + 回应飞盘相关但非规则的内容**。

⚠️ **但放开范围必须有边界**，否则会变成"句子里有『飞盘』两个字就全答"。
   owner 举的反例：
> 「他说：『我用飞盘打到一个人会怎么样？』但他没有说是在哪里打到的。
>  如果是在现实生活中和别人打架…你回答了他，这就属于回答了飞盘比赛之外的内容，
>  **你是不是在帮助他去构成暴力呢？**」

## 核心判据（owner 原话）
> 「**什么时候拒答？** 当他**诱导我们去回答飞盘运动之外的内容**时。」

## 三岔口（不是开关）
| 路 | 判据 | 走哪条链路 |
|---|---|---|
| `RULE` | 想弄明白**规则**怎么算 | 严谨链路（检索+条款+铁律），**一个字不动** |
| `RELATED` | 和**打飞盘这件事**有关（含情绪、队友、训练、装备、约球） | 对话链路（可以共情，规则仍不许编） |
| `OFF_TOPIC` | 和飞盘运动**无关**，只是句子里带了"飞盘"或纯闲聊 | 友好拒答 + 引导去别的工具 |
| `HARM` | **明确在求帮助去伤害别人** | 直接拒（唯一一种硬拒） |

## ⚠️⚠️ 三条设计铁律
1. **判不准就往严里走**：`RULE` 优先于 `RELATED`，`RELATED` 优先于放开。
   宁可少共情一次，不可放进来一个会被编造的问题。
2. **歧义不硬拒，而是问一句**。owner 那个"用飞盘打了人"的例子：
   它**可能是场上冲撞（该答）也可能是场下打架（不该答）** ⇒
   正确做法是**问清楚**，不是拒答 ——
   ⚠️ 拒答会让**真的在场上被撞的人**更难过，正是 owner 要避免的。
3. **`HARM` 的门槛必须极高**：只有**明确**在求帮助伤害他人时才走。
   绝不允许因为出现"打人/撞人"这类词就判 HARM ——
   那些正是规则问题的核心词汇（12.6、17.1 讲的全是这个）。
"""
