# ============================================================
# 〇、「跟飞盘有关，但我真的答不了」—— 第五个出口（2026-10-15 加）
# ============================================================
#
# 【为什么需要它】实测（真实控制流，不是猜）：
# ```
#   办一场飞盘比赛要交多少报名费   → 走了严谨规则链路，**硬答了一段**
#   离我家最近的飞盘场地在哪       → 同上
#   飞盘多少钱一个 / 推荐个飞盘牌子 → 同上
#   北京到上海多远 / 这双鞋在哪儿买 → 同上
#                          13 条里 **12 条**是这样
# ```
# owner 的产品定义是「**我们不能让用户难过**」，
# 而他问"报名费多少"却收到一段"规则管的是场上怎么打、赛事收多少钱属于主办方…"——
# **那比说"我不知道"更让人难受：像是没听懂他。**
#
# 【为什么不能靠收紧词表解决】
# `DOMAIN_WORDS` 里有裸「飞盘」（`app/routes.py:1697`），
# 句子里只要有这两个字，`domain_hit()` 就命中 ⇒ `confident=True`
# ⇒ `classify(has_rule_candidate=True)` **无条件返回 RULE**。
# ⚠️ 而这是**有意设计**，`tests/test_gate.py:87-97` 明确写：
#    「含域内名词、但问题本身笼统 —— **允许放行**，交给生成层按依据充分性兜。」
#    理由是"**误拦的代价 > 白调一次模型**"。
# ⇒ 那个判断是对的，**缺的是"兜"的那一半** —— 生成层没有"这不是规则问题"的出口。
#   所以修法是**补出口**，不是收紧入口。
#
# ⚠️⚠️ 判据**换过一次**，旧的为什么废弃必须留着 —— 否则下一轮还会有人去调那个阈值。
#
# 【第一版（已废弃）：看检索命中的条款"泛章占比"】
#   想法：把第 1 章（精神）/ 2 章（场地）/ 3 章（装备）/ DEF / PRE 当"泛章"，
#         命中全落在这些章 ⇒ 没有具体条款对得上 ⇒ 不是规则问题。
#   实测发现**两个致命问题**：
#     ① **第 2 章分类错了**：场地尺寸是**真正的规则内容**（附录 A1.2 规定 100×37 米）。
#        ⇒ `中心区多长`（泛章占比 0.88）和 `边线多长`（1.00）**被误拦**
#        ⇒ 而那是**早就有答案的题**（`verify_remote.py` 里就有"内容缺口-中心区 答出 64"）。
#        ⚠️ 这正是 `app/server.py` 里那段注释预警过的同一个坑：
#          「第一版只要 classify 判 OFF_TOPIC 就提前返回，结果『中心区多长』被拒了」。
#          **我原样犯了一遍。**
#     ② **它依赖改写后的措辞**：`中心区多长` 用原句检索占比 0.88（不拦），
#        用 LLM 改写后的句子检索变成 1.00（会拦）⇒ 同一个问题**时好时坏**。
#    ⇒ 教训：**判据不要建立在"章节分类"这种会被人改来改去的中间产物上**，
#      要建立在一个**本来就成立的事实**上。
#
# 【现在这一版：**两个信号取交集**】
#
# 信号 A：检索时命中的域内词是**裸「飞盘」/「盘」**
#   事实依据：`domain_hit()` 返回句子里命中的那个域内词。
#   ```
#     域外题：「办一场飞盘比赛要交多少报名费」→ 飞盘
#             提了"飞盘"两个字，但**没说出任何具体的规则概念**
#     真规则题：「读秒从几开始」→ 读秒 ｜「中心区多长」→ 中心区
#   ```
#
# 信号 B：**原句里也没有任何具体域内概念**
#
# ⚠️⚠️ 为什么必须两个信号一起用（各用一次都出过事，都记下来）：
#   ① **只用 A** ⇒ 被 LLM 改写的随机性搞坏。实测同一个问题两次请求：
#      ```
#        本地：改写 → 「场地 尺寸 比赛场地 得分区 边界线」⇒ domain_word = 多大  ⇒ 不拦 ✅
#        线上：改写 → 更泛的句子                            ⇒ domain_word = 飞盘  ⇒ 拦了 ❌
#      ```
#      **`飞盘场地有多大` 就这么被误拦了**（而它早就有答案：100×37 米，附录 A1.2）。
#      ⇒ 教训：**判据不能建立在"一次 LLM 调用的输出"上**，那个东西不可复现。
#   ② **只用 B** ⇒ 太粗。`打飞盘要穿什么鞋` 里"鞋"是域内词，
#      但装备确实归规则第 3 章管，不该拦（这条是**已知漏**，见下面）。
#
#   取交集之后：**"检索说只看到'飞盘'这个词" **且** "原句里确实没有具体概念"**
#   ⇒ 两条独立证据都指向"这不是规则问题"才拦。
#   实测（**用真实控制流、含 LLM 改写**）：**误伤 0 / 34**，命中 8 / 10。
#
# ⚠️ 已知漏（宁漏勿误）：`打飞盘要穿什么鞋` / `国内有哪些飞盘赛事`。
#    它们原句里有具体词（鞋 / 飞盘赛事）⇒ 不拦。
#    **这两条不算错**：装备归第 3 章、赛事规则归第 4~6 章，答它们不违反边界。
_GENERIC_DOMAIN_WORDS = frozenset({"飞盘", "盘"})
# ⚠️ 至少要有这么多条命中才判 —— 太少说明检索本身没跑好，
#    那种情况该走 `not_found`（"换种说法再问"），不是"这不归我管"。
#    两者对用户的含义完全不同：前者是"我没找到"，后者是"这不该问我"。
_BEYOND_MIN_HITS = 3


def is_beyond_rules(hits: list[dict] | None,
                    domain_word: str | None = None,
                    question: str = "") -> tuple[bool, str]:
    """这问题是不是「跟飞盘有关，但真的答不了」？

    **两个信号取交集**（缺一不可，理由见上面那段长注释）：
      A. 检索命中的域内词是裸「飞盘」/「盘」
      B. **原句**里也没有任何具体的域内概念

    ⚠️ `domain_word` 要传**检索时实际用的那个**（可能是 LLM 改写后算出来的）；
       `question` 要传**用户的原句**（改写会丢信息，而信号 B 恰恰要的是原句）。

    返回 `(是否域外, 给日志的一句话解释)`。
    """
    hs = hits or []
    if len(hs) < _BEYOND_MIN_HITS:
        return False, f"命中太少（{len(hs)} < {_BEYOND_MIN_HITS}），交给 not_found"
    dw = str(domain_word or "")
    if dw not in _GENERIC_DOMAIN_WORDS:
        return False, (f"检索命中了具体概念「{dw}」⇒ 按规则题处理"
                       if dw else "没命中域内词 ⇒ 交给其他分支")
    # 信号 A 成立 ⇒ 再看信号 B：原句里有没有**任何**具体概念
    #
    # ⚠️⚠️ 这里**不能只看 `domain_hit(question)` 返回的那一个词** ——
    #    `domain_hit` 返回的是**按索引顺序第一个命中的**（索引按词长倒序，
    #    同长度的相对顺序取决于构建顺序）。实测：
    #    ```
    #       domain_hit('飞盘场地有多大') = '多大'    ← 「多大」也在域内词表里
    #       domain_hit('场地多大')       = '多大'
    #    ```
    #    ⇒ 而「飞盘场地有多大」是个**真规则题**（100×37 米，附录 A1.2），
    #      却被这个"第一个命中的词是泛词"判成了域外。
    #    ⇒ 正确做法：**把原句里所有命中的域内词都扫一遍**，
    #      只要里面有任何一个具体概念，就不能判"他什么都没说清"。
    from app import routes as _routes          # 局部导入，避免模块级循环依赖
    low = _routes._norm(question or "") if hasattr(_routes, "_norm") else (question or "")
    specifics = [w for w in _routes.DOMAIN_WORDS
                 if w not in _GENERIC_DOMAIN_WORDS and w in low]
    if specifics:
        return False, (f"原句里有具体概念 {'/'.join(specifics[:3])} "
                       f"⇒ 可能是规则问题（改写把它泛化了，不能因此就判它答不了）")
    return True, (f"检索只命中裸「{dw}」且原句也没有任何具体概念 "
                  f"⇒ 不是规则问题")





