# ⚠️⚠️ 只有"**在求帮助去伤害别人**"才算。判据要求**同时**满足：
#    ① 有明确的**向他人施害**的动词＋宾语
#    ② **没有任何**场上/比赛/运动语境
#    —— 缺任何一条都不判 HARM。
# ⚠️ 这正是 owner 那个例子的处理方式：只问"用飞盘打了人会怎么样"**不判 HARM**
#    （可能是场上冲撞），而是走 `needs_clarify`（问一句）。
_HARM_ACT = ("打人", "打伤", "打他", "揍", "报复", "教训他", "教训一下",
             "弄死", "砍", "捅", "砸他", "砸人", "下毒", "偷", "抢他", "毁掉",
             "曝光他", "人肉", "威胁", "恐吓")
# ⛔⛔【已试过并撤回】2026-10-13 往上面加过「打到」，**是错的**：
#   「用飞盘打到一个人会怎么样」被判成 HARM ⇒ 直接硬拒。
#   而 owner 那个例子的**正解是问一句**（可能是场上冲撞，该答）。
#   ⚠️ 教训：**「打到」本身中性**（"球打到他了"），
#      问题不在于动词，在于**没有"击打"的意图**。
#      ⇒ 判 HARM 要看**施害动词**（打人/砸他/报复/教训），不是"碰到"。
_HARM_AIM = ("怎么", "如何", "怎样", "能不能", "可不可以", "有没有办法", "教我",
             "帮我", "想", "要", "该", "违法吗", "犯法吗", "会怎么样", "后果")
# 场外语境信号：出现这些说明**不是**在问比赛（反而更可疑）
_FIELD_CONTEXT = ("场上", "比赛", "赛场上", "训练", "打球", "打比赛", "规则",
                  "犯规", "违例", "联赛", "锦标赛", "公开赛", "积分赛")

# ⚠️ **单字施害字** —— 只用于 `needs_clarify`（"问一句"），**不用于 `is_harm_seeking`**。
#    理由：这两件事的**代价完全不对称**：
#      · 问一句 ⇒ 判宽了只是多问一句，无害
#      · 硬拒   ⇒ 判宽了会拒掉**真的在场上被撞的人**，正是 owner 要避免的
#    ⇒ 阈值本来就不该一样，所以分成两份词表。
_HARM_CHARS = "打砸揍砍捅伤"

# ============================================================
# 五、指代不明（「他那样」「这种情况」）
# ============================================================
# ⚠️ 这类问句**信息不够**，但**不是离题** —— 该走追问，不该拒答。
#    实测：「这种情况算吗」走追问是对的；「他一直那样我怎么办」被误当离题。
_PRONOUN = ("那样", "这样", "那种", "这种", "那个", "这个", "刚才", "刚刚",
            "他那样", "他这样", "那一下", "这一下", "那种情况", "这种情况")

# ⚠️ 2026-10-20（质量闸门 g025/g026）：**明确的非规则诉求**。
#    「队友总是不跑位，我该怎么跟他说」和「推荐一双飞盘鞋」都被检索塞了
#    候选条款（跑位→12.x，鞋→1.6/1.7），于是 `has_rule_candidate` 把路走成
#    rule；模型只能在规则链路里说"这不在规则范围"，用户拿到的是一段绕路回答。
#    ⇒ 在 `has_rule_candidate` **之前**认这类诉求，直接走 related。
#    ⚠️ 但必须让**规则问句信号**一票否决：有"算不算/怎么判/规则/犯规"时
#       仍然是规则题（否则「队友不跑位算不算越位」会被误改道）。
_RELATED_REQUEST = (
    "怎么跟他说", "怎么和他说", "怎么沟通", "怎么开口", "跟队友说",
    "队友总是", "队友一直", "队内气氛", "队里气氛",
    "推荐", "买什么", "哪款", "穿什么鞋", "选什么鞋", "装备推荐",
    "怎么练", "训练计划", "怎么提高",
)
_RULE_QUESTION_MARK = (
    "算不算", "算吗", "怎么算", "怎么判", "规则", "犯规", "违例", "条款", "判罚",
)


def is_related_request(text: str) -> bool:
    """是「飞盘相关、但明确不是规则问题」的诉求吗（沟通/装备/训练建议）？"""
    t = text or ""
    if not _hit(t, _RELATED_REQUEST):
        return False
    return not _hit(t, _RULE_QUESTION_MARK)


def _hit(text: str, terms) -> list[str]:
    return [t for t in terms if t in text]


def is_frisbee_related(text: str) -> bool:
    """和「打飞盘这件事」有关吗？

    ⚠️ 单字「盘」要排除"键盘/盘算/盘问"这类；其余词按子串判。
    """
    t = (text or "").lower()
    if not t:
        return False
    # 先看有没有"键盘"这种会把单字「盘」误判的词
    if any(b in t for b in _FRISBEE_SINGLE_BLOCK):
        # 把被挡掉的部分挖掉再判
        for b in _FRISBEE_SINGLE_BLOCK:
            t = t.replace(b, "")
    for term in _FRISBEE_TERMS:
        if term in _FRISBEE_SINGLE:
            continue
        if term in t:
            return True
    return any(s in t for s in _FRISBEE_SINGLE)


def has_emotion(text: str) -> bool:
    return bool(_hit(text or "", _EMOTION))


def has_pronoun(text: str) -> bool:
    return bool(_hit(text or "", _PRONOUN))


def is_off_topic_signal(text: str) -> bool:
    return bool(_hit(text or "", _OFF_TOPIC))


def is_off_domain_task(text: str) -> bool:
    """是「和飞盘无关的任务请求」吗（提到了飞盘，但要的不是飞盘的事）？

    ⚠️ owner 的边界原话：
      「字句里有『飞盘』这两个字眼，和飞盘这项运动没什么关系，
        这个时候就应该直接拒绝回答。」（例子：用飞盘写首诗）
    ⚠️ 判据是**要做什么**，不是**提到了什么**：
       写诗/翻译/写代码/讲笑话 —— 换成任何主题都能做 ⇒ 不该在这儿做。
    """
    t = text or ""
    if not _hit(t, _TASK_OFF_DOMAIN):
        return False
    return bool(_hit(t, _TASK_VERB))


def is_topic_unknown(text: str) -> bool:
    """**纯情绪、但看不出在说什么话题**（"今天被打爆了，好烦"）。

    ⚠️ 为什么单独判这一类（2026-10-13 踩过）：
       它在字面上**没有任何飞盘词**，但"打爆"在飞盘里就是**输惨了**。
       直接判成离题 ⇒ 正是 owner 要避免的"让他更难过"。
       ⇒ 正确做法是**问一句**（共情 + 请他说说什么事），而不是拒答。
    ⚠️ 要求"有情绪"且"没有任何话题线索" ——
       有话题线索的会走 RELATED，有离题信号的会走 OFF_TOPIC。
    """
    t = text or ""
    if not has_emotion(t):
        return False
    if is_frisbee_related(t):
        return False
    if is_off_topic_signal(t):
        return False
    return True


def is_harm_seeking(text: str) -> bool:
    """**明确**在求帮助伤害他人吗？门槛极高。

    ⚠️ 必须同时满足：① 施害动作 ② 求方法/问后果 ③ **没有**场上语境。
       缺一条就不判 —— 因为「打人/撞人」正是规则条款的核心词汇（12.6、17.1）。
    """
    t = text or ""
    if not _hit(t, _HARM_ACT):
        return False
    if not _hit(t, _HARM_AIM):
        return False
    if _hit(t, _FIELD_CONTEXT):
        return False          # 有场上语境 ⇒ 是在问规则，不是求施害
    return True


def needs_clarify(text: str) -> bool:
    """信息不够、但不该拒答 —— 该问一句。

    ⚠️ 判据：**带指代词**且**没有**具体动作/结果词。
       owner 的例子（"用飞盘打了人会怎么样"）走的是这条：
       它字面完整，但**场景不明**（场上还是场下），问一句比拒答好。
    """
    t = text or ""
    if not t.strip():
        return True
    if has_pronoun(t):
        return True
    # "用飞盘打人"这类：有飞盘 + 施害动作，但**没有场上语境** ⇒ 场景不明
    # ⚠️ 这里**不看 `is_frisbee_related`** —— 实测「用飞盘打到一个人会怎么样」
    #    里的"打到"不在词表里，会被判成"与飞盘无关"，从而走成 OFF_TOPIC。
    #    owner 那个例子的正解是**问一句**，不是拒答。
    # ⚠️ 判据退到最直接的两条：**有「飞盘」** + **有施害字眼**（字或词都算）。
    #    刻意比 `_HARM_ACT` 宽 —— 这里只是"问一句"，判宽了没风险；
    #    而 HARM 是硬拒，必须判严。两者**阈值本来就不该一样**。
    if "飞盘" in t and not _hit(t, _FIELD_CONTEXT):
        if _hit(t, _HARM_ACT) or any(c in t for c in _HARM_CHARS):
            return True
    return False


def classify(text: str, *, has_rule_candidate: bool = False) -> dict:
    """把一句话分到四条路之一。

    ⚠️ `has_rule_candidate` 由调用方传（检索是否给出了候选条款）。
       传 True 时**一律走 RULE** —— 有条款就别乱改道。

    返回 `{route, why, need_clarify}`；`why` 是给日志和测试看的判据说明。
    """
    t = (text or "").strip()
    if not t:
        return {"route": OFF_TOPIC, "why": "空输入", "need_clarify": False}

    # ① 危害意图（门槛极高，只在这一处硬拒）
    if is_harm_seeking(t):
        return {"route": HARM, "why": "明确在求帮助伤害他人，且无场上语境",
                "need_clarify": False}

    # ② 「和飞盘无关的任务请求」⇒ 即使提到了飞盘也拒
    #    ⚠️ 必须排在 frisbee 判断**之前**，否则"帮我用飞盘写首诗"会被判成飞盘相关
    if is_off_domain_task(t):
        return {"route": OFF_TOPIC, "why": "和飞盘无关的任务请求（只是提到了飞盘）",
                "need_clarify": False}

    # ②b 明确的非规则诉求（沟通/装备/训练建议）⇒ 对话链路。
    #    ⚠️ 必须在 `has_rule_candidate` 之前：检索对"跑位/鞋"会给候选条款，
    #       但这不是规则问题（质量闸门 g025/g026）。
    #    ⚠️ 必须**同时与飞盘相关**：否则「推荐个餐厅」会被"推荐"误判成 related
    #       （2026-10-20 全量单测抓到的回归）。
    if is_frisbee_related(t) and is_related_request(t):
        return {"route": RELATED, "why": "明确的非规则诉求（沟通/装备/训练建议）",
                "need_clarify": False}

    frisbee = is_frisbee_related(t)
    emo = has_emotion(t)
    off = is_off_topic_signal(t)

    # ③ 有条款候选 ⇒ 一律走严谨链路（不抢路）
    if has_rule_candidate:
        return {"route": RULE, "why": "检索已给出候选条款", "need_clarify": False}

    # ④ 场景不明（可能是场上，也可能是场下）⇒ 问一句，不拒答
    #    ⚠️ 但**明确离题信号优先**：2026-10-13 实测「盘算一下这个月花了多少」
    #       因为含"这个"被判成指代追问（"盘算"被挡掉后只剩单字"盘"）。
    #       ⇒ 有离题信号且**与飞盘无关**时，不该走追问。
    if is_off_topic_signal(t) and not frisbee:
        return {"route": OFF_TOPIC, "why": "有明确离题信号且与飞盘无关",
                "need_clarify": False}
    if needs_clarify(t):
        return {"route": RELATED, "why": "指代/场景不明，该问一句",
                "need_clarify": True}

    # ⑤ ⚠️ 纯情绪、看不出话题 ⇒ 问一句（不是拒答）
    #    理由见 `is_topic_unknown`：飞盘圈里的"打爆了"字面没有飞盘词，
    #    判成离题正是 owner 要避免的"让他更难过"。
    if is_topic_unknown(t):
        return {"route": RELATED, "why": "有情绪但没有话题线索 ⇒ 问一句",
                "need_clarify": True}

    # ⑥ 飞盘相关（含情绪）⇒ 对话链路
    if frisbee and not off:
        why = "飞盘相关" + ("且有情绪" if emo else "")
        return {"route": RELATED, "why": why, "need_clarify": False}

    # ⑦ ⚠️ 情绪 + 飞盘 + 离题信号**同时出现** ⇒ 不确定，问一句
    #    （例："今天好烦，天气也不好" —— 看不出他想问什么）
    if emo and off:
        return {"route": RELATED, "why": "有情绪也像离题 ⇒ 问一句",
                "need_clarify": True}

    # ⑧ 其余 ⇒ 离题
    #    ⚠️ owner 要的共情是"**飞盘带来的**难过"，不是通用陪聊。
    #       通用陪聊豆包做得更好，硬答反而显得假。
    why = "有情绪但与飞盘无关（不做通用陪聊）" if emo else "与飞盘运动无关"
    return {"route": OFF_TOPIC, "why": why, "need_clarify": False}


def stats() -> dict:
    """给自检/文档用：各词表规模。"""
    return {
        "frisbee_terms": len(_FRISBEE_TERMS),
        "emotion_terms": len(_EMOTION),
        "off_topic_terms": len(_OFF_TOPIC),
        "harm_terms": len(_HARM_ACT) + len(_HARM_AIM),
        "pronoun_terms": len(_PRONOUN),
    }
