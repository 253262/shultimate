# -*- coding: utf-8 -*-
"""助手（Assistant）预设 —— 对应 RAGFlow「聊天 → 新建助理」的配置形态。

设计约束（重要）：
  预设**只能追加**风格提示（尾部一段），**不能覆盖** generator.SYSTEM_PROMPT 的铁律。
  原因：铁律里有两条是"防编造"的承重条款 —— ①飞盘无裁判，禁止出现「裁判/处罚」；
  ②依据不足必须明说"规则没规定"。若让助手预设能改写这两条，等于把系统的可信度
  交给一个下拉框。所以这里只做"表达方式"的差异化，不做"行为准则"的差异化。

字段与 RAGFlow 助理设置的对应：
  id      内部标识（前端传参用）
  name    助理名称
  desc    一句话说明（助手卡片副标题）
  style   追加到系统提示词尾部的风格要求；空串 = 用默认风格
  top_n   该助手的默认召回条数（可为 None，用全局 TOP_K）
  cite    默认是否展示引用面板
  opener  开场白（对话空态时显示）
"""
from __future__ import annotations

# 【2026-10-06 精简：4 个 -> 2 个】
# 原来有「标准助手 / 新手模式 / 场上速查 / 争议复盘」四个，删掉了「新手模式」与「场上速查」。
# 删的理由（owner 决定，我看到的是同一个原因）：
#   · 「新手模式」的提示词里写着「不要省略『该怎么做』，新手最需要知道场上具体动作」——
#     它是在**主动要求把回答撑长**，而当时的默认形态是"越短越好"，两者对着干。
#     ⚠️ 2026-10-12 更新：**那条"越短越好"已经删掉了**
#     （owner 说「答完就停、多写一个字都在稀释答案」已过时，见 `generator.py` 头部注释）。
#     现在判据是「**贴不贴题**」而不是字数 ⇒ 当初这条删除理由的**前提变了**，
#     但结论不变：「新手模式」仍然该删，因为新人**不知道自己该点哪一个**
#     （见下面第三条），而不是因为长度冲突。
#   · 「场上速查」想要的效果（只要结论和条款号），现在**已经变成默认形态**了 ——
#     保留它等于让用户去选一个本来就该默认的行为。
#   · 四个预设里有两个是"同一件事的不同长度"，用户还得先判断自己属于哪一种 ——
#     而新人根本不知道自己该点哪个。**默认给最短的那个，想要更多的点「展开细节」。**
# ⇒ 现在只留两个真正不同的**场景**：日常问答（默认，无追加提示）与争议复盘（要讲认定标准）。
#
# ⚠️ 预设**只能追加**风格提示（尾部一段），**不能覆盖** generator.SYSTEM_PROMPT 的铁律。
ASSISTANTS: list[dict] = [
    {
        "id": "standard",
        "name": "标准模式",
        "desc": "直接回答你问的那件事；想多看依据和边界，点「展开细节」",
        "style": "",
        "top_n": None,
        "cite": True,
        "opener": "用大白话描述场上的情况就行，不需要知道条款号。",
    },
    {
        "id": "captain",
        "name": "争议复盘",
        "desc": "把认定标准讲清楚，指出双方各自主张对应哪条，但不替你下结论",
        "style": (
            "\n## 本次的风格要求（追加）\n"
            "提问者可能正与对手就这次判罚有分歧：\n"
            "- 把规则「怎么认定这件事」讲清楚，而不是直接判谁对\n"
            "- 如果双方各自的主张在规则里都有对应条款，分别列出来\n"
            "- 明确指出「谁犯规」这一判断按规则由场上队员自己做出（无裁判）\n"
            "- 涉及事实不清时，说明需要先确认哪些现场细节\n"
            "⚠️ 仍然按「直答 + `<!--more-->` + 细节」的格式写：\n"
            "  直答段给「按规则该怎么认定」；双方各自依据哪条、现场细节，放进细节段，\n"
            "  不要堆在第一段里。"
        ),
        "top_n": None,
        "cite": True,
        "opener": "把当时的情况和双方说法都说出来，我告诉你规则怎么认定。",
    },
]

_BY_ID = {a["id"]: a for a in ASSISTANTS}
DEFAULT_ID = "standard"


def get(assistant_id: str | None) -> dict:
    """按 id 取助手；未知 id 回落到默认助手（不报错，保证前端传什么都能用）。"""
    return _BY_ID.get((assistant_id or "").strip(), _BY_ID[DEFAULT_ID])


def listing() -> list[dict]:
    """给前端用的精简清单（不含内部 style 全文，但带风格摘要）。"""
    return [
        {
            "id": a["id"],
            "name": a["name"],
            "desc": a["desc"],
            "top_n": a["top_n"],
            "cite": a["cite"],
            "opener": a["opener"],
            "custom_style": bool(a["style"]),
        }
        for a in ASSISTANTS
    ]
