def alias_hits(text: str) -> set[str]:
    """返回别名命中的定义 id 集合。"""
    low = (text or "").lower()
    out: set[str] = set()
    for alias, ids in _ALIAS_INDEX:
        if alias in low:
            out.update(ids)
    return out


def match_routes(text: str) -> list[str]:
    """返回命中的族名（去重，保持 ROUTES 顺序）。

    ⚠️ 条件线索（见 `_CONDITIONAL_HINTS`）：表里登记的线索**必须句中有语境词**
    才触发。判据在 `_cond_ok`，本函数是唯一入口 —— 别在别处重写一份
    （重写就分叉，AGENTS.md §13「域内/术语判定只能有一份实现」同一个道理）。
    """
    low = _norm(text)
    hit: set[str] = set()
    for hint, name in _INDEX:
        if hint not in low:
            continue
        if hint in _CONDITIONAL_HINTS and not _cond_ok(low, hint):
            continue
        hit.add(name)
    return [n for n, _, _, _, _ in ROUTES if n in hit]


def _cond_ok(low: str, hint: str) -> bool:
    """条件线索的语境判断：句中必须出现任一必需语境词。

    ⚠️ `low` 必须是**已 `_norm` 过**的小写文本；本函数只被 `match_routes` 调用。
    ⚠️ 语境词表是**已 `_norm` 的字面量**，所以中文不受影响，但若将来加入
       含大写或「哪儿」的词，必须自己先过一遍 `_norm`（见 `_build` 对线索词的处理）。
    """
    return any(w in low for w in _CONDITIONAL_HINTS[hint])


def _alias_in(low: str, w: str) -> bool:
    """这个英文术语别名是否出现在问句里（大小写已由 _norm 处理）。

    判据分两档，理由见下面两条实测：
    ① ≥5 字符（spirit / pivot / turnover / marker…）直接子串。
       这么长的词不会被别的英文单词包住，子串不会误报。
    ② <5 字符（pull / catch / force / guard）必须落在**词边界**上，
       否则「recall my order」「catch a cold」全被误判成域内
       （实测：召回召回召回，闸门形同虚设）。

    ⚠️⚠️ 边界判断不能直接用 `\b`（2026-10-10 实测，这是本轮最隐蔽的一个坑）：
       Python 的 `\b` 只把 [A-Za-z0-9_] 当词字符，**中文不是词字符**，
       所以中英混排时右边根本不存在边界：
           re.search(r"\bpull\b",  "pull是什么")      → None  ← 漏放
           re.search(r"\bCatch\b", "Catch 是什么意思") → None  ← 漏放
       而这恰恰是中文用户问术语的标准姿势，等于把新手第一道墙又砌回去。

       ⇒ 边界只检查**英文字母/数字**两侧：紧邻中文时视为边界成立
         （中文不可能出现在英文单词内部，不会带来误报）。
    """
    if len(w) >= 5:
        return w in low
    return re.search(rf"(?<![A-Za-z0-9_]){re.escape(w)}(?![A-Za-z0-9_])", low) is not None


def term_aliases_in(low: str) -> list[str]:
    """这句问句里出现的全部官方英文术语别名。

    ⭐ 这是**术语判定的唯一入口**：`domain_hit` 与 `smalltalk._domain_words`
    都调它。两处各写一份就会分叉（2026-10-10 实测）——
    「force怎么用」在闸门那里放行、在 smalltalk 那里却没有域内证据
    → 被判成闲聊 → 新手问术语只得到一句客套话。

    ⚠️ 入参必须是**已 `_norm` 过**的小写文本（调用方负责）。
    """
    # 求解语气：中英两种都要认。英文那组为 "What is a Catch" /
    # "How to pull" 这类纯英文问句（实测漏放过）。
    has_ctx = (any(cw in low for cw in _CONTEXT_WORDS)
               or re.search(r"(是|什么|啥|意思|怎么|如何|定义|解释|这|那)", low) is not None
               or re.search(r"\b(what|whats|what's|how|why|meaning|mean|means|"
                            r"define|definition|explain|is|are|does|do)\b", low) is not None)
    out: list[str] = []
    for w in _TERM_ALIAS_INDEX:
        # 飞盘独有的词：无条件放行（huck / spirit / pivot…）——
        # 这些词在普通英语里根本不出现，放行不会带来误报。
        if w in _UNIQUE_ALIASES:
            if _alias_in(low, w):
                out.append(w)
            continue
        # 通用词（pull / catch / force / guard）：需飞盘语境或求解语气陪衬。
        # 实测不放陪衬就会炸：「catch a cold」「pull up a chair」「force of habit」。
        if has_ctx and _alias_in(low, w):
            out.append(w)
    return out


def domain_hit(text: str) -> str | None:
    """问题里有没有**任何**飞盘域内的基础词。命中返回那个词，否则 None。

    **只用于相关性闸门放行，绝不参与打分。**

    为什么需要它：族只覆盖"需要判断的争议场景"，368 条规则有 190 条
    （场地/装备/队伍/比赛开始等事实性章节）不属于任何族 →
    那些问题无论检索多准都会被闸门拦掉（实测"边线和端线是什么"正解排第 1
    仍被拒答）。闸门的职责是挡住**和飞盘无关**的问题。

    ⚠️ 不要把它接进 forced_split —— 那等于凭空造出 20 个巨型兜底族，
       会把各章总则全部抬进候选，破坏已调好的排序。
    """
    low = _norm(text)
    for w in _DOMAIN_INDEX:
        if w in low:
            return w

    # ---- 官方英文术语（2026-10-10）----
    # ⚠️ 判定逻辑不在这里写第二遍：统一走 term_aliases_in()。
    #   实测分叉过一次（2026-10-10）—— 两处各写一份时，
    #   「force怎么用」在闸门这里放行、在 smalltalk 那里却没有域内证据
    #   → 被判成闲聊 → 新手问术语只得到一句客套话。
    for w in term_aliases_in(low):
        return w
    return None


def _expand(prefixes: list[str], available: set[str]) -> set[str]:
    """把条号前缀展开为语料里实际存在的条号。

    前缀 "8.5" -> 所有 id == "8.5" 或 id 以 "8.5." 开头的条款。
    available 是语料里实际存在的全部 id，用来避免生成不存在的条号。
    """
    out: set[str] = set()
    for pre in prefixes:
        if pre in available:
            out.add(pre)
        pref = pre + "."
        out.update(i for i in available if i.startswith(pref))
    return out


def forced_split(text: str, available: set[str]
                 ) -> tuple[dict[str, float], dict[str, float], list[str]]:
    """按线索返回 **(主条款权重表, 辅条款权重表, 命中的族名列表)**。

    返回的是 **id -> 加分倍数** 的 dict，不是纯集合：
    每个族的第 5 个字段是"优先级倍数"，高特异度的小族调高倍数后，
    可以压过同时被触发的宽泛大族（"读秒太快" → 18.1.1.1.3 要压过 9.x 全族）。

    主/辅必须分开返回，不能合成一个表：调用方要给主条款更大的加分。
    合成一个就会出现"31 条齐步走"的自我稀释（实测正解反而掉出前 8）。
    同一 id 被多个族命中时取**最大**倍数（最具体的那个族说话）。
    """
    routes = match_routes(text)
    primary: dict[str, float] = {}
    aux: dict[str, float] = {}

    def _put(bucket: dict[str, float], ids: set[str], mult: float) -> None:
        for i in ids:
            if mult > bucket.get(i, 0.0):
                bucket[i] = mult

    for name, _, pri, auxp, mult in ROUTES:
        if name not in routes:
            continue
        _put(primary, _expand(pri, available), mult)
        _put(aux, _expand(auxp, available), mult)

    for i in list(aux):          # 主条款优先，不重复计分
        if i in primary:
            del aux[i]
    return primary, aux, routes


def forced_ids(text: str, available: set[str]) -> tuple[set[str], list[str]]:
    """兼容旧签名的薄封装：返回 (主+辅 合并集合, 族名)。

    新代码请直接用 forced_split()，否则拿不到主辅区分与优先级倍数。
    """
    primary, aux, routes = forced_split(text, available)
    return set(primary) | set(aux), routes
