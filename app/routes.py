# ---------- 口语变体归一化（2026-10-06）----------
# **为什么**：审计集里一大批失败根本不是"没写线索"，而是**同一句话的两种口语写法**：
#   · 「我该从哪儿开始发盘」 vs 线索 `从哪开始`
#   · 「判完之后大家该站哪儿」 vs 线索 `站哪里`
#   · 「咋整 / 咋办 / 啥情况」 vs 线索里的 `怎么 / 什么`
# 逐条加变体会让线索表翻倍且永远漏；改成在**匹配时**统一归一化：
# 查询和线索词都过一遍 _norm()，两种写法自动收敛成一种。
#
# ⚠️ 归一化只做"同义口语收敛"，不做同义词替换（"扔"不会变成"掷"）——
#    后者会把不同情形混在一起，正是族间抢位的根源。
def _norm(s: str) -> str:
    t = (s or "").lower()
    # 只收敛**儿化音**：「从哪儿开」≡「从哪儿开」，统一成长形式「哪里」。
    # ⚠️ 2026-10-06 两条实测教训，都写在这里免得后来人重踩：
    #   ① 一开始把「哪里」也并到「哪」→ `站哪里` 这类宽线索开始匹配所有
    #      「站哪…」问法（14.3 掉 8 名、18.2.5.1 掉 7 名）。
    #   ② 用「哪」当短形式也一样危险：`从哪开` 会命中所有「从哪开始」
    #      （两道"得分区失误了从哪开始"的 FAQ 直接掉出前 5）。
    #   ⇒ 收敛方向必须选**长形式**（哪儿→哪里），这样：
    #      · 「从哪儿开」有专属线索 `从哪儿开`，不会牵动「从哪开始」；
    #      · 短线索（`从哪开`）根本不存在，误触面积为零。
    t = t.replace("哪儿", "哪里")
    return t


def _build() -> None:
    for name, hints, _primary, _aux, _mult in ROUTES:
        for h in hints:
            _INDEX.append((_norm(h), name))


_build()


