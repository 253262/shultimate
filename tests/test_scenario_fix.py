class TestRouteTables(unittest.TestCase):
    """族表结构守卫：正解必须落在**主档**（辅档吃 ROUTE_BONUS_AUX，太轻）。"""

    @classmethod
    def setUpClass(cls):
        cls.by_name = {n: (h, p, a, m) for n, h, p, a, m in routes.ROUTES}

    def test_new_families_primary_clauses(self):
        for fam, want in [
            ("计满", "13.2.2"),
            ("精神暂停", "1.7.4"),
            ("出手后抢断", "13.1.2"),
            ("掩护", "18.3.1"),
            ("危险动作", "17.1"),
            ("表现继续", "16.3"),
            # 第二批
            ("死盘活盘", "8.1.5"),
            ("开盘直接出界", "7.12"),
            ("相互抵消犯规", "17.9.1"),
            ("相互抵消犯规", "17.9.2"),
            ("张臂挡人", "12.9"),
            # 第三批（2026-10-06 全库审计：368 条逐条反向出题）
            ("犯规之后接着打", "16.1"),
            ("犯规之后接着打", "16.2.3"),
            ("犯规之后接着打", "16.2.4.1"),
        ]:
            with self.subTest(fam=fam, want=want):
                self.assertIn(fam, self.by_name, f"族「{fam}」不存在")
                _, primary, _, _ = self.by_name[fam]
                self.assertIn(want, primary,
                              f"族「{fam}」的主档应含 {want}（放辅档吃不到 ROUTE_BONUS）")

    def test_hint_tables_stay_clean(self):
        """线索词表本身不许有重复项和空白项（重复会掩盖笔误）。"""
        for name, hints, _, _, _ in routes.ROUTES:
            with self.subTest(fam=name):
                self.assertEqual(len(hints), len(set(hints)), f"族「{name}」线索词有重复")
                self.assertFalse([h for h in hints if not h or not h.strip()],
                                 f"族「{name}」线索词有空项")

    def test_family_count_not_shrunk(self):
        """68 个族是两批修复后的规模，只许多不许少（防误删）。"""
        self.assertGreaterEqual(len(routes.ROUTES), 68)


class TestGeneratorPrompt(unittest.TestCase):
    """生成层提示词守卫（无法行为化，只能查源码）。

    ⚠️ 断言前先剥注释：`generator.py` 的注释里会引用被禁写法作反例，
    直接 assertNotIn 会被自己的注释绊红（已踩过 4 次）。
    """

    def setUp(self):
        src = (ROOT / "app" / "generator.py").read_text(encoding="utf-8")
        # 先剥 `//` 行注释，再剥 `/* */` 块注释 —— 顺序反了会把后面整段代码吞掉
        src = re.sub(r"//[^\n]*", "", src)
        self.src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)

    def test_refusal_rule_still_there(self):
        """最高优先级那条铁律不许被删：不确定就说不确定。"""
        self.assertIn("规则里没有规定这一点", generator.SYSTEM_PROMPT)
        self.assertIn("不要猜", generator.SYSTEM_PROMPT)

    def test_over_refusal_clause_added(self):
        """新增约束：条款能回答时不许以『没提到这个动作名』为由拒答。"""
        p = generator.SYSTEM_PROMPT
        self.assertIn("不等于", p)
        self.assertIn("没提到这个动作", p)
        # 也不能反过来变成"有条款就一定对"——必须保留"依据条款"的前提
        self.assertIn("只能依据【规则条款】回答", p)

    def test_infraction_vs_foul_distinction_in_prompt(self):
        """**违例不停止比赛**这条必须写死在提示词里。

        2026-10-05 实测：同一道「读秒太快要不要停下来」，前后两次跑出**相反**结论
        （一次"不用停"✓、一次"比赛随即停止"✗）。根因是候选里只有"什么算读秒过快"
        （18.1.1.1.x），没有 15.2/18.1.3 的后果条，模型只能靠常识猜。
        修法两处：① routes.py 把 18.1.3 抬进主档；② 提示词写明 15.1~15.3 的分类。
        这里守第 ② 处 —— 它没法行为化（要真调大模型），只能查源码。
        """
        p = generator.SYSTEM_PROMPT
        self.assertIn("违例", p)
        self.assertIn("比赛不停止", p)
        # 三类必须同时出现，否则模型会退化成"一律停止"
        for w in ("犯规", "违规", "违例"):
            with self.subTest(word=w):
                self.assertIn(w, p)

    def test_no_referee_words_leak_into_prompt(self):
        """无裁判是极限飞盘的基本事实，提示词里不许把『裁判』写成角色。

        用计数比对而不是 assertNotIn：提示词里**必须**出现"没有裁判"来纠正模型，
        所以"含有这两个字"本身不是违规，"以裁判为主语的指令句"才是。
        """
        banned = ["由裁判判罚", "裁判决定", "裁判吹罚", "交由裁判"]
        for b in banned:
            with self.subTest(word=b):
                self.assertNotIn(b, generator.SYSTEM_PROMPT)


